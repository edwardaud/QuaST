#!/usr/bin/env python3
"""Generate `realistic_noav.prm` from `realistic_E.prm` for
docs/ASPECT_REALISTIC_COMPARE.md section 15 (the alpha_AV switch-off run).

Only three things change, and exactly one of them is functional:

  1. `Output directory`            run_E  ->  run_noav
  2. `List of output variables`    material properties
                                   -> material properties, artificial viscosity
     (diagnostic output only: the `artificial viscosity` visualization plugin,
      source/postprocess/visualization/artificial_viscosity.cc)
  3. a new `subsection Discretization / subsection Stabilization parameters`
     with `set beta = 0` -- the artificial viscosity itself.

Why beta: in this version (2.5.0-pre, 340c0d018) the entropy-viscosity cap is

    maximum_viscosity = beta * (rho*cp) * |u|_max * h_K
        source/simulator/entropy_viscosity.cc:209-211
    alpha_AV = min(maximum_viscosity, cR*h^2*max_residual/entropy_variation)
        :236
    ... and :213-218 returns maximum_viscosity unchanged for the first two
    steps, :204-207 returns beta*(k/L)*h_K when |u| = 0.

With beta = 0 every one of those branches is exactly 0, so alpha_AV == 0 on
every cell (it is already forced to 0 on the Dirichlet wall cells, :371-448).
cR (default 0.11) is left at its default because min(0, cR-term) = 0; that is
checked by the assertion below: the generated card must not contain any other
`Stabilization parameters` entry.

Usage:  python3 make_noav.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.join(HERE, "realistic_E.prm")

OLD_DIR = "set Output directory                       = run_E"
NEW_DIR = "set Output directory                       = run_noav"

OLD_VIS = "    set List of output variables = material properties\n"
NEW_VIS = ("    # `artificial viscosity` is added so the alpha_AV field can be\n"
           "    # measured on this run itself (same plugin as realistic_E6.prm).\n"
           "    set List of output variables = material properties, artificial viscosity\n")

ANCHOR = "subsection Postprocess\n"

BLOCK = """# ---------------------------------------------------------------------------
# THE ONLY FUNCTIONAL CHANGE vs realistic_E.prm: the artificial viscosity of
# the temperature equation is switched off completely.
#
# beta is the cap of the entropy-viscosity stabilisation:
#     maximum_viscosity = beta * (density*cp) * |u|_max * h_K
#     alpha_AV = min(maximum_viscosity, cR*h^2*max_residual/entropy_variation)
# (source/simulator/entropy_viscosity.cc:209-211 and :236; the same field is
# what the boundary heat flux uses as kappa_eff = max(k, alpha_AV),
# heat_flux_map.cc:203-212, and what the temperature assembly uses as
# max(k, alpha_AV), assemblers/advection.cc:172-184).  With beta = 0 the cap
# is exactly 0, so alpha_AV == 0 on every cell -- including the two early
# steps that return maximum_viscosity directly (:213-218) and the |u| = 0
# branch (:204-207).  cR = 0.11 (the default) is left untouched:
# min(0, cR-term) = 0.
#
# Everything else (geometry, BCs, heating, material/phase model, AMR strategy
# and fractions, CFL, maximum time step, solver tolerances, VTU/checkpoint
# cadence, end time) is copied verbatim from realistic_E.prm.
# ---------------------------------------------------------------------------
subsection Discretization
  subsection Stabilization parameters
    set beta = 0
  end
end

"""

HEADER = """# ---------------------------------------------------------------------------
# ASPECT counterpart run `run_noav` of docs/ASPECT_REALISTIC_COMPARE.md
# section 15: realistic_E.prm with the artificial viscosity disabled
# (`set beta = 0` under Discretization/Stabilization parameters).
# Generated by make_noav.py; every other line is identical to realistic_E.prm.
# ---------------------------------------------------------------------------
"""

src = open(BASE).read()
assert src.count(OLD_DIR) == 1, src.count(OLD_DIR)
assert src.count(OLD_VIS) == 1, src.count(OLD_VIS)
assert src.count(ANCHOR) == 1, src.count(ANCHOR)
assert "Stabilization" not in src and "beta" not in src

out = src.replace(OLD_DIR, NEW_DIR).replace(OLD_VIS, NEW_VIS).replace(ANCHOR, BLOCK + ANCHOR)
out = HEADER + out

# the only functional difference is the one Stabilization-parameters entry
assert out.count("\n    set beta = 0\n") == 1   # the one real card entry
assert "set cR" not in out and "set alpha" not in out

path = os.path.join(HERE, "realistic_noav.prm")
with open(path, "w", newline="\n") as f:
    f.write(out)
print("wrote", path, len(out), "chars")
