#!/usr/bin/env python3
"""Generate the IC-perturbation ensemble cards of docs/ASPECT_REALISTIC_COMPARE.md
section 14 from `realistic_E.prm`.

Only the initial-temperature seed and the output directory differ from
`realistic_E.prm`; every physics/numerics block (geometry, BCs, heating,
material, AMR, solver, VTU and checkpoint cadence) is copied verbatim.

Members (the perturbation is a change of the IC only):
  1  A1 0.05  -> 0.0501  (+0.2 %; max |dT| in the IC = 0.1 K)
  2  A1 0.05  -> 0.0502  (+0.4 %; max |dT| = 0.2 K)
  3  a 0.2 rad phase shift of the A1 cosine (a different seed realization,
     same amplitudes/wavenumbers; max |dT| = 10 K, 1 % of the 1000 K drop)

Usage:  python3 make_ens.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.join(HERE, "realistic_E.prm")

OLD_A = "A1=0.05, A2=0.02"
OLD_COS = "A1*sin(pi*z/d)*cos(2*pi*x/Lx)"
NEW_COS = "A1*sin(pi*z/d)*cos(2*pi*x/Lx + phase)"
OLD_DIR = "set Output directory                       = run_E"
NEW_DIR_FMT = "set Output directory                       = run_ens%d"
HEADER = (
    "# ---------------------------------------------------------------------------\n"
    "# ENSEMBLE MEMBER %d of docs/ASPECT_REALISTIC_COMPARE.md section 14.\n"
    "# Identical to realistic_E.prm except the initial-condition seed (%s)\n"
    "# and the output directory.  Generated by make_ens.py.\n"
    "# ---------------------------------------------------------------------------\n")

# member -> (A1, A2, phase, label)
MEMBERS = {
    1: (0.0501, 0.02, None, "A1 +0.0001 (+0.2 %)"),
    2: (0.0502, 0.02, None, "A1 +0.0002 (+0.4 %)"),
    3: (0.05, 0.02, 0.2, "A1 phase +0.2 rad (different seed; max dT 10 K)"),
}

src = open(BASE).read()
assert src.count(OLD_A) == 1, src.count(OLD_A)
assert src.count(OLD_COS) == 1, src.count(OLD_COS)
assert src.count(OLD_DIR) == 1, src.count(OLD_DIR)

for i, (a1, a2, phase, label) in MEMBERS.items():
    s = src.replace(OLD_A, "A1=%g, A2=%g" % (a1, a2))
    if phase is not None:
        s = s.replace("A1=0.05, A2=0.02, Lx",
                      "A1=0.05, A2=0.02, phase=%.15g, Lx" % phase)
        s = s.replace(OLD_COS, NEW_COS)
    s = s.replace(OLD_DIR, NEW_DIR_FMT % i)
    s = HEADER % (i, label) + s
    out = os.path.join(HERE, "realistic_ens%d.prm" % i)
    open(out, "w").write(s)
    print("wrote", out, " A1=%g A2=%g phase=%s" % (a1, a2, phase))
